#!/usr/bin/env python3
"""
Reliable GitHub Stars fetcher that writes languages.md and topics.md in the
exact format produced by `starred` (https://github.com/maguowei/starred).

Uses the GitHub REST API (/users/{username}/starred) so it never hits the
GraphQL RESOURCE_LIMITS_EXCEEDED error that `starred` triggers on large star
lists, and fails loudly with a non-zero exit code on API errors.
"""

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from collections import OrderedDict

DEFAULT_CATEGORY = "Others"
TEXT_LENGTH_LIMIT = 200

HEADER = """<!--lint disable awesome-contributing awesome-license awesome-list-item match-punctuation no-repeat-punctuation no-undefined-references awesome-spell-check-->
# Awesome Stars [![Awesome](https://awesome.re/badge.svg)](https://github.com/sindresorhus/awesome)

> A curated list of my GitHub stars! Generated by [starred](https://github.com/maguowei/starred).

## Contents
"""

LICENSE_TEMPLATE = """
## License

[![CC0](http://mirrors.creativecommons.org/presskit/buttons/88x31/svg/cc-zero.svg)](https://creativecommons.org/publicdomain/zero/1.0/)

To the extent possible under law, [{username}](https://github.com/{username}) has waived all copyright and related or neighboring rights to this work.
"""


def html_escape(text: str) -> str:
    return text.replace(">", "&gt;").replace("<", "&lt;")


def fetch_starred_repos(username: str, token: str, include_private: bool = False) -> list:
    repos = []
    page = 1
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "awesome-list-star-sync",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"

    while True:
        url = f"https://api.github.com/users/{username}/starred?per_page=100&page={page}"
        req = urllib.request.Request(url, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                batch = json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            body = e.read().decode("utf-8", errors="replace")[:300]
            raise RuntimeError(f"GitHub API HTTP {e.code} on page {page}: {body}") from e
        except urllib.error.URLError as e:
            raise RuntimeError(f"GitHub API network error on page {page}: {e}") from e

        if not batch:
            break

        for r in batch:
            if r.get("private") and not include_private:
                continue
            repos.append({
                "full_name": r["full_name"],
                "url": r["html_url"],
                "description": (r.get("description") or ""),
                "language": r.get("language") or "",
                "topics": r.get("topics") or [],
            })

        if len(batch) < 100:
            break
        page += 1

    return repos


def render_markdown(repos: list, username: str, by_topic: bool = False, sort: bool = True) -> str:
    repo_dict = {}
    for r in repos:
        desc = html_escape(r["description"]).replace("\n", "").replace("\r", "").strip()[:TEXT_LENGTH_LIMIT] if r["description"] else ""
        entry = [r["full_name"], r["url"], desc]
        if by_topic:
            categories = r["topics"] or [DEFAULT_CATEGORY.lower()]
            for cat in categories:
                repo_dict.setdefault(cat, []).append(entry)
        else:
            cat = r["language"] or DEFAULT_CATEGORY
            repo_dict.setdefault(cat, []).append(entry)

    if sort:
        repo_dict = OrderedDict(sorted(repo_dict.items(), key=lambda item: item[0]))

    lines = [HEADER]
    for category in repo_dict:
        anchor = "-".join(category.lower().split())
        lines.append(f"- [{category}](#{anchor})")
    lines.append("")

    for category, items in repo_dict.items():
        lines.append(f"## {category.replace('#', '# #')} \n")
        for full_name, url, desc in items:
            lines.append(f"- [{full_name}]({url}) - {desc}")
        lines.append("")

    lines.append(LICENSE_TEMPLATE.format(username=username))
    return "\n".join(lines) + "\n"


def atomic_write(path: str, content: str) -> None:
    tmp_path = f"{path}.tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        f.write(content)
    os.replace(tmp_path, path)


def main() -> int:
    parser = argparse.ArgumentParser(description="Fetch GitHub stars and write languages.md / topics.md locally.")
    parser.add_argument("--username", required=True, help="GitHub username")
    parser.add_argument("--token", default=os.environ.get("GITHUB_TOKEN", ""), help="GitHub token")
    parser.add_argument("--languages", default="", help="Output path for languages.md")
    parser.add_argument("--topics", default="", help="Output path for topics.md")
    parser.add_argument("--private", action="store_true", help="Include private repos")
    args = parser.parse_args()

    if not args.languages and not args.topics:
        print("Error: specify at least one of --languages or --topics", file=sys.stderr)
        return 1

    repos = fetch_starred_repos(args.username, args.token, include_private=args.private)
    if not repos:
        print(f"Error: fetched 0 starred repositories for {args.username}", file=sys.stderr)
        return 1

    if args.languages:
        atomic_write(args.languages, render_markdown(repos, args.username, by_topic=False, sort=True))
        print(f"✅ Wrote {args.languages} ({len(repos)} starred repos)")

    if args.topics:
        atomic_write(args.topics, render_markdown(repos, args.username, by_topic=True, sort=True))
        print(f"✅ Wrote {args.topics} ({len(repos)} starred repos)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
